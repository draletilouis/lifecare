/* The page for one department, rendered by scripts/build.js from data/departments.js.
   The shell blocks are left empty here: the build fills them from index.html.
   Text that comes from data/site.js is marked with data-fact so it stays in step. */

module.exports = function renderDepartment(d, { site, icon, escapeHtml: e, category, hours, related, all }) {
  const title = `${d.name} | ${site.name}, Arua`;
  const list = (items) =>
    `<ul class="check-list">\n${items.map((item) => `                <li>${icon('check')}<span>${e(item)}</span></li>`).join('\n')}\n              </ul>`;

  const services = d.services
    .map(([name, text]) => `            <li class="service">\n              <h3>${e(name)}</h3>\n              <p>${e(text)}</p>\n            </li>`)
    .join('\n');

  const warning = d.warning
    ? `
          <div class="callout callout--urgent" role="note">
            <p class="callout__title">${icon('alert')} ${e(d.warning.title)}</p>
            <ul>
${d.warning.items.map((item) => `              <li>${e(item)}</li>`).join('\n')}
            </ul>
            <p class="callout__action">Call <a href="tel:" data-fact-href="tel:phones.emergency"><strong data-fact="phones.emergency"></strong></a> or come straight to Accident &amp; Emergency, open 24 hours.</p>
          </div>
`
    : '';

  const visiting = d.showVisiting
    ? `
          <h2 id="visiting">Visiting hours</h2>
          <p>Visitors help patients recover. To let patients rest and the team work, please visit during these times, and keep to two visitors at a bedside.</p>
          <table class="hours-table" style="margin-top:1.25rem">
            <tbody>
              <!-- build:visiting-hours -->
              <!-- /build:visiting-hours -->
            </tbody>
          </table>
`
    : '';

  const faqs = d.faqs
    .map(([q, a]) => `            <details class="faq__item">\n              <summary>${e(q)}${icon('chevron')}</summary>\n              <p>${e(a)}</p>\n            </details>`)
    .join('\n');

  const relatedCards = related
    .map((r) => `          <a href="${r.url}" class="dept-tile">
            <span class="dept-tile__name">${e(r.name)}</span>
            <span class="dept-tile__text">${e(r.card)}</span>
            <span class="dept-tile__more">Learn more ${icon('arrow')}</span>
          </a>`)
    .join('\n');

  const sideNav = all
    .map((x) => `              <li><a href="${x.url}"${x.slug === d.slug ? ' aria-current="page"' : ''}>${e(x.name)}</a></li>`)
    .join('\n');

  const photo = d.photo
    ? `
          <figure class="page-hero__media">
            <!-- Placeholder photograph (Unsplash). Replace with the hospital's own: see assets/photos/CREDITS.md -->
            <img src="/assets/photos/${d.photo.file}-1600.jpg" srcset="/assets/photos/${d.photo.file}-800.jpg 800w, /assets/photos/${d.photo.file}-1600.jpg 1600w" sizes="(max-width: 1024px) 100vw, 42vw" alt="${e(d.photo.alt)}" width="1600" height="1200" fetchpriority="high"${d.photo.position ? ` style="object-position: ${d.photo.position}"` : ''} />
          </figure>`
    : '';

  const schema = {
    '@context': 'https://schema.org',
    '@type': 'MedicalWebPage',
    name: title,
    description: d.summary,
    about: { '@type': 'MedicalClinic', name: `${d.name}, ${site.name}`, parentOrganization: { '@id': `${site.url}/#hospital` } },
    breadcrumb: {
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Home', item: `${site.url}/` },
        { '@type': 'ListItem', position: 2, name: 'Departments', item: `${site.url}/departments/` },
        { '@type': 'ListItem', position: 3, name: d.name, item: `${site.url}/departments/${d.slug}/` },
      ],
    },
  };

  return `<!DOCTYPE html>
<!-- Generated by scripts/build.js from data/departments.js and templates/department.js. Edit those, not this file. -->
<html lang="en" class="no-js">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${e(title)}</title>
  <meta name="description" content="${e(d.summary)}" />
  <link rel="canonical" href="" />
  <meta property="og:type" content="website" />
  <meta property="og:site_name" content="${e(site.name)}" />
  <meta property="og:title" content="${e(title)}" />
  <meta property="og:description" content="${e(d.summary)}" />
  <meta property="og:url" content="" />
  <meta property="og:image" content="" />
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:image" content="" />
  <script type="application/ld+json">
${JSON.stringify(schema, null, 2).replace(/^/gm, '    ')}
  </script>
  <!-- shell:head -->
  <!-- /shell:head -->
</head>
<body>
  <!-- shell:icons -->
  <!-- /shell:icons -->

  <!-- shell:header -->
  <!-- /shell:header -->

  <main id="main">
    <section class="page-hero">
      <div class="container">
        <nav class="breadcrumb" aria-label="Breadcrumb">
          <ol>
            <li><a href="/">Home</a></li>
            <li><a href="/departments/">Departments</a></li>
            <li><span aria-current="page">${e(d.name)}</span></li>
          </ol>
        </nav>
        <div class="page-hero__grid">
          <div class="page-hero__content">
            <p class="eyebrow">${e(category.name)}</p>
            <h1>${e(d.name)}</h1>
            <p class="lead">${e(d.summary)}</p>
            <div class="page-hero__actions">
              <a href="/appointments/?department=${d.slug}" class="btn btn--primary btn--lg">Book an appointment</a>
              <a href="tel:" data-fact-href="tel:phones.main" class="text-link">${icon('phone')} Call reception</a>
            </div>
          </div>${photo}
        </div>
      </div>
    </section>

    <div class="facts">
      <dl class="container facts__list">
        <div>
          <dt>Hours</dt>
          <dd>${e(hours.time)}${hours.note ? `<small>${e(hours.note)}</small>` : ''}</dd>
        </div>
        <div>
          <dt>Reception</dt>
          <dd><a href="tel:" data-fact-href="tel:phones.main" data-fact="phones.main"></a><small>Appointments and questions</small></dd>
        </div>
        <div>
          <dt>Payment</dt>
          <dd>Cash, mobile money or insurance<small><a href="/patients/#paying" class="link">How payment works</a></small></dd>
        </div>
        <div class="facts__urgent">
          <dt>Emergency, 24 hours</dt>
          <dd><a href="tel:" data-fact-href="tel:phones.emergency" data-fact="phones.emergency"></a><small>Or come straight to A&amp;E</small></dd>
        </div>
      </dl>
    </div>

    <section class="section">
      <div class="container dept-layout">
        <article class="dept-main">
          <div class="prose">
${d.intro.map((p) => `            <p>${e(p)}</p>`).join('\n')}
          </div>

          <h2 id="services">What we offer</h2>
          <ul class="service-list">
${services}
          </ul>
${warning}
          <div class="two-lists">
            <div>
              <h2 id="when">When to come to us</h2>
              ${list(d.whenToCome)}
            </div>
            <div>
              <h2 id="bring">What to bring</h2>
              ${list(d.bring)}
            </div>
          </div>
${visiting}
          <h2 id="faq">Common questions</h2>
          <div class="faq">
${faqs}
          </div>

          <p class="disclaimer">${icon('info')} This page describes our services in general terms. It is not a substitute for advice from a clinician who has examined you.</p>
        </article>

        <aside class="dept-aside">
          <div class="aside-card aside-card--cta">
            <h2>See a clinician</h2>
            <p>Send an appointment request and our team will call you back to confirm a time.</p>
            <a href="/appointments/?department=${d.slug}" class="btn btn--primary btn--block">Request an appointment</a>
            <a href="https://wa.me/" data-fact-href="wa:phones.whatsapp" class="btn btn--whatsapp btn--block" target="_blank" rel="noopener noreferrer">${icon('whatsapp')} Message us on WhatsApp</a>
          </div>
          <nav class="aside-card" aria-label="All departments">
            <h2>All departments</h2>
            <ul class="side-nav">
${sideNav}
            </ul>
          </nav>
        </aside>
      </div>
    </section>

    <section class="section section--paper">
      <div class="container">
        <div class="section__head section__head--split">
          <h2>Related departments</h2>
          <a href="/departments/" class="text-link">All departments ${icon('arrow')}</a>
        </div>
        <div class="tile-grid">
${relatedCards}
        </div>
      </div>
    </section>
  </main>

  <!-- shell:footer -->
  <!-- /shell:footer -->
</body>
</html>
`;
};
