/* The page for one health information article, rendered by scripts/build.js from data/articles.js.
   The shell blocks are left empty here: the build fills them from index.html. */

module.exports = function renderArticle(a, { site, icon, escapeHtml: e, related, others }) {
  const title = `${a.title} | ${site.name}, Arua`;

  const section = (s) => {
    const paragraphs = (s.paragraphs || []).map((p) => `            <p>${e(p)}</p>`).join('\n');
    const list = s.list ? `            <ul>\n${s.list.map((li) => `              <li>${e(li)}</li>`).join('\n')}\n            </ul>` : '';
    if (s.urgent) {
      return `          <div class="callout callout--urgent article__urgent" role="note">
            <h2 class="callout__title">${icon('alert')} ${e(s.heading)}</h2>
${[paragraphs, list].filter(Boolean).join('\n')}
            <p class="callout__action">Call <a href="tel:" data-fact-href="tel:phones.emergency"><strong data-fact="phones.emergency"></strong></a> or come straight to Accident &amp; Emergency, open 24 hours.</p>
          </div>`;
    }
    return `          <h2>${e(s.heading)}</h2>
${[paragraphs, list].filter(Boolean).join('\n')}`;
  };

  const review = a.reviewedBy
    ? `Reviewed by ${e(a.reviewedBy)} · Updated ${e(a.updated)}`
    : `Updated ${e(a.updated)} · Awaiting review by a Life Care clinician`;

  const relatedLinks = related
    .map((r) => `            <li><a href="${r.url}">${e(r.name)} ${icon('arrow')}</a></li>`)
    .join('\n');

  const more = others
    .map((o) => `          <a href="/health/${o.slug}/" class="article-card">
            <span class="article-card__cat">${e(o.category)}</span>
            <span class="article-card__title">${e(o.title)}</span>
            <span class="article-card__meta">${o.readMinutes} min read</span>
          </a>`)
    .join('\n');

  const schema = {
    '@context': 'https://schema.org',
    '@type': 'MedicalWebPage',
    name: a.title,
    headline: a.title,
    description: a.summary,
    inLanguage: 'en',
    publisher: { '@id': `${site.url}/#hospital` },
    ...(a.reviewedBy ? { reviewedBy: { '@type': 'Person', name: a.reviewedBy } } : {}),
    breadcrumb: {
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Home', item: `${site.url}/` },
        { '@type': 'ListItem', position: 2, name: 'Health information', item: `${site.url}/health/` },
        { '@type': 'ListItem', position: 3, name: a.title, item: `${site.url}/health/${a.slug}/` },
      ],
    },
  };

  return `<!DOCTYPE html>
<!-- Generated by scripts/build.js from data/articles.js and templates/article.js. Edit those, not this file. -->
<html lang="en" class="no-js">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${e(title)}</title>
  <meta name="description" content="${e(a.summary)}" />
  <link rel="canonical" href="" />
  <meta property="og:type" content="article" />
  <meta property="og:site_name" content="${e(site.name)}" />
  <meta property="og:title" content="${e(a.title)}" />
  <meta property="og:description" content="${e(a.summary)}" />
  <meta property="og:url" content="" />
  <meta property="og:image" content="" />
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:image" content="" />
  <script type="application/ld+json">
${JSON.stringify(schema, null, 2).replace(/^/gm, '    ')}
  </script>
  <!-- shell:head -->
  <!-- /shell:head -->
</head>
<body>
  <!-- shell:icons -->
  <!-- /shell:icons -->

  <!-- shell:header -->
  <!-- /shell:header -->

  <main id="main">
    <section class="page-hero page-hero--article">
      <div class="container">
        <nav class="breadcrumb" aria-label="Breadcrumb">
          <ol>
            <li><a href="/">Home</a></li>
            <li><a href="/health/">Health information</a></li>
            <li><span aria-current="page">${e(a.category)}</span></li>
          </ol>
        </nav>
        <h1>${e(a.title)}</h1>
        <p class="lead">${e(a.summary)}</p>
        <p class="article__meta">${icon('clock')} ${a.readMinutes} min read <span aria-hidden="true">·</span> ${review}</p>
      </div>
    </section>

    <section class="section section--tight">
      <div class="container article-layout">
        <article class="article">
${a.sections.map(section).join('\n\n')}

          <p class="disclaimer">${icon('info')} This article gives general health information. It is not a substitute for advice from a clinician who has examined you. If you are worried, come and see us or call reception.</p>
        </article>

        <aside class="article-aside">
          <div class="aside-card aside-card--cta">
            <h2>Need to see a clinician?</h2>
            <p>Walk in to the outpatient clinic, or send a request and we will call you to confirm a time.</p>
            <a href="/appointments/" class="btn btn--primary btn--block">Request an appointment</a>
            <a href="https://wa.me/" data-fact-href="wa:phones.whatsapp" class="btn btn--whatsapp btn--block" target="_blank" rel="noopener noreferrer">${icon('whatsapp')} WhatsApp us</a>
          </div>
          <nav class="aside-card" aria-label="Related departments">
            <h2>Related departments</h2>
            <ul class="aside-links">
${relatedLinks}
            </ul>
          </nav>
        </aside>
      </div>
    </section>

    <section class="section section--paper">
      <div class="container">
        <div class="section__head section__head--split">
          <h2>More health information</h2>
          <a href="/health/" class="text-link">All articles ${icon('arrow')}</a>
        </div>
        <div class="article-grid">
${more}
        </div>
      </div>
    </section>
  </main>

  <!-- shell:footer -->
  <!-- /shell:footer -->
</body>
</html>
`;
};
